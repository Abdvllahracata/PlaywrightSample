import { APIRequestContext, APIResponse, expect } from '@playwright/test';
import { buildCustomer, buildOrder, buildPost, CartItem, Customer, PostPayload } from '../data/dataFactory';

/**
 * Client for API tests without a browser; baseURL is set by the fixture (env.apiUrl).
 * One instance is created per test, so the last response can be safely stored here (the equivalent of ScenarioContext in Reqnroll).
 */
export class ApiHelper {
  private lastResponse?: APIResponse;
  private lastPayload?: PostPayload;

  constructor(private readonly request: APIRequestContext) {}

  /** Response of the last request; throws an error when no request has been sent yet. */
  private get response(): APIResponse {
    if (!this.lastResponse) throw new Error('Belum ada request yang dikirim di scenario ini');
    return this.lastResponse;
  }

  async getPost(id: number): Promise<void> {
    this.lastResponse = await this.request.get(`/posts/${id}`);
  }

  /** Creates a new post; without an argument, a random payload is generated by dataFactory. */
  async createPost(payload: PostPayload = buildPost()): Promise<void> {
    this.lastPayload = payload;
    this.lastResponse = await this.request.post('/posts', { data: payload });
  }

  /** id from the last response, e.g. the id of a post that was just created. */
  async getResponseId(): Promise<number> {
    return (await this.response.json()).id;
  }

  async deletePost(id: number): Promise<void> {
    this.lastResponse = await this.request.delete(`/posts/${id}`);
  }

  /**
   * Creates a customer through the API and returns it with its new id, so a UI test can use data that was
   * prepared through the API. jsonplaceholder does not store it; the response only echoes the sent data.
   */
  async createCustomer(customer: Customer = buildCustomer()): Promise<Customer & { id: number }> {
    const response = await this.request.post('/users', { data: customer });
    expect(response.status(), 'Gagal membuat data pembeli lewat API').toBe(201);
    const body = await response.json();
    expect(body).toMatchObject({ ...customer });
    return body;
  }

  async deleteCustomer(id: number): Promise<void> {
    const response = await this.request.delete(`/users/${id}`);
    expect(response.status(), `Gagal menghapus data pembeli ${id} lewat API`).toBe(200);
  }

  /**
   * Saves products read from the UI cart through the API as an order record and returns its new id.
   * The response must contain exactly the products that were sent.
   */
  async createOrder(items: CartItem[]): Promise<number> {
    const payload = buildOrder(items);
    const response = await this.request.post('/posts', { data: payload });
    expect(response.status(), 'Gagal menyimpan pesanan lewat API').toBe(201);
    const body = await response.json();
    expect(body).toMatchObject(payload);
    return body.id;
  }

  /**
   * Fetches a user from the API and maps it to checkout customer data (test data sourced from the API).
   * The name is split into first and last name, and the address zipcode is used as the postal code.
   * The result goes through buildCustomer, so any field missing from the API is still filled with random data.
   */
  async fetchCustomer(userId: number): Promise<Customer> {
    const response = await this.request.get(`/users/${userId}`);
    expect(response.ok(), `Gagal mengambil data user ${userId} dari API`).toBeTruthy();
    const user = await response.json();
    const [firstName, ...lastName] = String(user.name).split(' ');
    return buildCustomer({ firstName, lastName: lastName.join(' '), postalCode: user.address?.zipcode });
  }

  expectStatus(status: number): void {
    expect(this.response.status()).toBe(status);
  }

  async expectPostId(id: number): Promise<void> {
    const body = await this.response.json();
    expect(body.id).toBe(id);
    expect(body.title).toBeTruthy();
  }

  /** A successful delete returns an empty object. */
  async expectEmptyBody(): Promise<void> {
    expect(await this.response.json()).toEqual({});
  }

  /** Ensures the response contains the sent payload along with a new id. */
  async expectBodyMatchesSentPayload(): Promise<void> {
    const body = await this.response.json();
    expect(body).toMatchObject(this.lastPayload!);
    expect(body.id).toBeDefined();
  }
}
